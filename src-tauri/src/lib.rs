//! The desktop shell.
//!
//! VoxLeaf keeps its domain logic in `voxleaf-core`, which owns the
//! database, the storage layer and the whole `/api` surface. This crate's job is
//! to give that a home: resolve the per-platform data directory, start the
//! embedded server, and open a window on it.
//!
//! The window is served from the same origin as the API on purpose. It is what
//! lets the UI keep using plain `fetch('/api/…')`, multipart XHR uploads with
//! real progress, and `<audio src>` range streaming exactly as the web app did —
//! with no CORS, no mixed content and no second code path.
//!
//! In release the compiled UI travels inside the binary: `build.rs` embeds
//! `dist/` as an `ASSETS` table and the server answers non-API paths from it,
//! falling back to the SPA shell so a deep link like `/library/lb_x` reloads
//! into the app. In dev the window points at Vite's dev server instead, which
//! proxies `/api` back to this process; the embedded copy (possibly stale, or
//! absent entirely) stays out of the way.

// The compiled frontend, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/assets.rs"));

use std::net::SocketAddr;
use std::time::Duration;

use axum::body::Body;
use axum::http::{header, StatusCode};
use axum::response::{IntoResponse, Response};
use tauri::{Manager, WebviewUrl, WebviewWindowBuilder};

/// Bind the API server, retrying a handful of ports so a busy machine still
/// starts. Returns the bound address.
async fn bind_server(state: voxleaf_core::api::AppState) -> anyhow::Result<SocketAddr> {
    let first: u16 = std::env::var("VOXLEAF_PORT")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(7931);

    // `service_fn` over a plain `async fn` keeps the service's `Future`
    // concrete, so the router's `S::Future: Send` bound is provable — an
    // `impl Service<...>` return type would hide it.
    let router = voxleaf_core::api::router(state, tower::service_fn(spa_response));

    let mut last_error = None;
    for offset in 0..20u16 {
        let addr = SocketAddr::from(([127, 0, 0, 1], first + offset));
        match tokio::net::TcpListener::bind(addr).await {
            Ok(listener) => {
                tokio::spawn(async move {
                    if let Err(error) = axum::serve(listener, router).await {
                        tracing::error!(%error, "the embedded API server stopped");
                    }
                });
                tracing::info!(%addr, "embedded API server listening");
                return Ok(addr);
            }
            Err(error) => {
                tracing::warn!(%addr, %error, "port unavailable, trying the next one");
                last_error = Some(error);
            }
        }
    }

    Err(anyhow::anyhow!(
        "could not bind a local port: {}",
        last_error.map(|error| error.to_string()).unwrap_or_default()
    ))
}

pub fn run() {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "info,voxleaf_core=info".into()),
        )
        .init();

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .setup(|app| {
            // Data lives where the platform says app data lives, so the library
            // survives upgrades and is backed up with the rest of the app.
            let data_dir = app.path().app_data_dir()?;
            let config = voxleaf_core::config::init(data_dir);
            tracing::info!(dir = %config.data_dir.display(), "data directory ready");

            let database = voxleaf_core::db::Database::open(&config.database_path)
                .map_err(|error| anyhow::anyhow!("could not open the database: {error}"))?;

            let state = voxleaf_core::api::AppState::new(
                database,
                (*config).clone(),
                voxleaf_core::services::Services::new(config),
            );

            let addr = tauri::async_runtime::block_on(bind_server(state))?;

            // Dev loads Vite's dev server (hot reload; it proxies `/api` back
            // to us). Release — or a debug binary run without the dev server,
            // which the reachability probe catches — loads our own embedded
            // copy from the same origin as the API.
            let url = dev_server_url(app.handle()).unwrap_or_else(|| format!("http://{addr}/"));

            WebviewWindowBuilder::new(app, "main", WebviewUrl::External(url.parse()?))
                .title("VoxLeaf")
                .inner_size(1280.0, 860.0)
                .min_inner_size(900.0, 600.0)
                // The upload dialogs take their files from HTML5 drag-and-drop,
                // so the webview must receive the drop rather than the shell.
                .disable_drag_drop_handler()
                .build()?;

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running VoxLeaf");
}

/// The dev server's URL, but only when it is actually a dev run *and* the
/// server answers. `tauri dev` starts Vite before this process, but a debug
/// binary launched straight from cargo would otherwise open a dead window.
fn dev_server_url(app: &tauri::AppHandle) -> Option<String> {
    use std::net::ToSocketAddrs as _;

    if !cfg!(debug_assertions) {
        return None;
    }
    let url = app.config().build.dev_url.as_ref()?;
    let host = url.host_str()?;
    let port = url.port_or_known_default()?;

    // Blocking DNS on a hostname that is almost always "localhost"; the probe
    // runs once during startup, before any window exists.
    let reachable = (host, port)
        .to_socket_addrs()
        .ok()
        .and_then(|mut addrs| addrs.next())
        .is_some_and(|address| {
            std::net::TcpStream::connect_timeout(&address, Duration::from_millis(250)).is_ok()
        });

    reachable.then(|| url.to_string())
}

/// Serve the embedded UI: an exact file hit first, then the SPA shell for
/// anything else — that is what makes a reload of a deep link land in the app.
///
/// A path that looks like a file (it has an extension) but is not in the table
/// gets a plain 404 instead of the shell: handing HTML to a script or stylesheet
/// request only turns a missing asset into a confusing parse error.
async fn spa_response(
    request: axum::http::Request<Body>,
) -> Result<Response, std::convert::Infallible> {
    Ok(asset_response(request.uri().path()))
}

/// One response for one URL path out of the embedded table.
fn asset_response(path: &str) -> Response {
    let not_embedded = || {
        (
            StatusCode::NOT_FOUND,
            "This copy of the frontend was not embedded; run `npm run build` and rebuild.",
        )
            .into_response()
    };

    if let Some((_, bytes)) = ASSETS.iter().find(|(url, _)| *url == path) {
        return file_response(path, bytes);
    }

    let looks_like_a_file = path.rsplit('/').next().is_some_and(|last| last.contains('.'));
    if looks_like_a_file {
        return (StatusCode::NOT_FOUND, "Not found.").into_response();
    }

    match ASSETS.iter().find(|(url, _)| *url == "/index.html") {
        Some((_, shell)) => file_response("/index.html", shell),
        None => not_embedded(),
    }
}

/// Headers for one embedded file. `content_type` rides on a `'static` str
/// because every extension maps to a constant.
fn file_response(path: &str, bytes: &[u8]) -> Response {
    // The shell references its assets by content hash, so only the shell
    // itself must never be cached; a fresh one is a small file.
    let cache_control = if path.ends_with(".html") {
        "no-cache"
    } else {
        "public, max-age=31536000, immutable"
    };

    Response::builder()
        .status(StatusCode::OK)
        .header(header::CONTENT_TYPE, content_type(path))
        .header(header::CONTENT_LENGTH, bytes.len().to_string())
        .header(header::CACHE_CONTROL, cache_control)
        .body(Body::from(bytes.to_vec()))
        .unwrap_or_else(|_| StatusCode::INTERNAL_SERVER_ERROR.into_response())
}

fn content_type(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or_default() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "json" => "application/json; charset=utf-8",
        "map" => "application/json",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
