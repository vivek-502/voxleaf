//! Embed the built frontend into the binary.
//!
//! The window is served from the same origin as the API, so the compiled UI
//! travels inside the executable rather than as loose files beside it. This
//! script walks `../dist` and writes an `ASSETS` table (URL path → bytes,
//! via `include_bytes!`) into `OUT_DIR`, which `lib.rs` includes.
//!
//! `beforeBuildCommand` runs `npm run build`, so `../dist` exists before
//! cargo compiles this crate in a bundle build. A bare `cargo check` or the
//! dev server may run before the frontend was ever built — the table is
//! simply empty then, and the shell serves API requests only.
//!
//! Note that the dev server's output is watched too: `cargo:rerun-if-changed`
//! on a directory makes cargo scan it recursively, so renaming a hashed
//! asset re-runs this script.

use std::path::{Path, PathBuf};

fn main() {
    tauri_build::build();

    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dist = manifest.join("../dist");
    println!("cargo:rerun-if-changed={}", dist.display());

    let mut entries: Vec<(String, String)> = Vec::new();
    collect(&dist, &dist, &mut entries);
    entries.sort();

    // A plain comment: `//!` would be an inner doc comment, which the
    // `include!` in lib.rs does not accept outside a module boundary.
    let mut generated = String::from(
        "// Generated by build.rs — every file in `dist/`, keyed by URL path.\n\
         pub(crate) static ASSETS: &[(&str, &[u8])] = &[\n",
    );
    for (url, file) in entries {
        // `{:?}` gives a properly escaped Rust string literal for both the
        // URL path (always ASCII-ish) and the absolute file path.
        generated.push_str(&format!(
            "    ({url:?}, include_bytes!({file:?})),\n",
            url = url,
            file = file,
        ));
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("assets.rs");
    std::fs::write(&out, generated).expect("could not write the embedded asset list");
}

/// Depth-first walk collecting `(URL path, absolute path)` pairs, rooted so
/// that URLs start with `/`.
fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    let Ok(read) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in read.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        let Ok(rel) = path.strip_prefix(root) else {
            continue;
        };
        let url = format!("/{}", rel.to_string_lossy().replace('\\', "/"));
        out.push((url, path.to_string_lossy().into_owned()));
    }
}
